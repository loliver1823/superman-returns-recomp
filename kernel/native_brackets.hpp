// Scope kinds (one per entry-table row).
enum Kind : uint8_t {
  kEntry = 0,     // external XDK entry point (data/native/xdk_entry_classes.tsv)
  kTable = 1,     // setter reached only through the device tables (xdk_table_setters.tsv)
  kFlush = 2,     // GpuCommandBufferFlush_sub_820FD8C0 (bracket split)
  kSwitch = 3,    // GpuCmdBufBeginNewSegment_sub_820FCF90 (bracket split)
  kWait = 4,      // GPU fence / ring waits (time bucket)
  kRingWrite = 5, // GpuRingUpdateWritePointer_sub_820FD218 (stamps ring dwords)
  kInternal = 6,  // other device internals worth a bracket (the pump driver)
};

// Entry-class codes (column `class` of the TSVs) for the coverage report.
enum EntryClass : uint8_t {
  kClsKeep = 0, kClsEmitter = 1, kClsResSync = 2, kClsDead = 3, kClsInternal = 4,
};

