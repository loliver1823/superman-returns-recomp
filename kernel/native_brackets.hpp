// The nearest interval ending at or below `phys` and the next one above it
// (context for an UNSTAMPED report). false = none.
bool neighbours(uint32_t phys, Interval* prev, Interval* next);
// Ring dword owner (index into the 64 KB primary ring) - consumed (cleared) by the read.
Stamp takeRingStamp(uint32_t ringIndex);
// Clear the stamps of a consumed ring packet (all its dwords), so a dword a later
// writer reuses can never inherit a stale owner.
void clearRingStamps(uint32_t ringIndex, uint32_t dwords);

// Id of the bracket open on the calling thread (0 = none). gfx/native_device keys
