// NATIVE ROADMAP N0 (docs/NATIVE_ROADMAP.md §4.1, §7 N0.0 / N0.3): observe-only
// instrumentation on every XDK D3D entry point (and the few device-internal
// functions that split or wait), shared by two gates, both default OFF:
//
//   SR_NATIVE_FRAMESPLIT=1  [NATIVE_FRAMESPLIT] - per presented frame on each
//                           presenting thread: time inside the XDK D3D range,
//                           inside its fence/ring waits, inside kernel imports,
//                           and the rest (game code). The E5 speed gate.
//   SR_NATIVE_BRACKETS=1    brackets keyed by (device, thread): each OUTERMOST
//                           XDK call records the command-buffer range it wrote
//                           (dev+0x28 cursor before/after, split at the segment
//                           switch 820FCF90 and the flush 820FD8C0), and the
//                           ring writer 820FD218 records the ring dwords it
//                           published. gfx/pm4_coverage looks each executed
//                           packet up here: ACCOUNTED (an XDK entry wrote it) or
//                           UNSTAMPED (no bracket covers it = an inlined/missed
//                           site, the discovery the native plan needs).
//
// Neither gate changes guest state: every scope reads guest memory only (the
// VdGlobalDevice cell, the device cursor and ring write index) and always
// delegates to __imp__ exactly once. Shims are generated by
// scripts/gen_native_brackets.py into kernel/native_brackets.gen.cpp; overrides
// that already existed for an entry carry SR_NATIVE_SCOPE(0xVA) as their first
// statement instead (the generator fails if one is missing).

