// iter-467 native-a P2 trace: observe hooks on shimmed table entries (the generated shims have no
// hook of their own). `before` runs with the entry's arguments in ctx, `after` with its return value;
// ctx is the PPCContext*. One load + branch per shimmed call when no hook is set.
extern bool g_hooksOn;
