struct XdkScope {
  int idx;
  uint32_t state = 0;
  uint64_t tsc0 = 0;
  bool active;
  bool hooked;
  void* ctxp;
  // A template so this header needs only the forward declaration of PPCContext;
  // it is instantiated in the override TUs, where the type is complete.
  template <class Ctx>
  XdkScope(int i, Ctx& ctx) : idx(i), active(g_anyOn && i >= 0), hooked(g_hooksOn && i >= 0), ctxp(&ctx) {
    if (active) scopeEnter(idx, uint32_t(ctx.lr), ctx.r13.u32, &tsc0, &state);
    if (hooked) hookEnter(idx, &ctx);
  }
  ~XdkScope() {
    if (hooked) hookLeave(idx, ctxp);
    if (active) scopeLeave(idx, tsc0, state);
  }
  XdkScope(const XdkScope&) = delete;
  XdkScope& operator=(const XdkScope&) = delete;
};

