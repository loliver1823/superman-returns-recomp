def bgfa(ents):
    """TOC-last named BGFA1.05 like tools/difftest/mod_manager_test.cpp bgfa()."""
    s = bytearray(0x40)
    s[0:8] = b"BGFA1.05"
    name_width = max([16] + [len(name.encode("latin1")) + 1 for name, _ in ents])
    offs = []
    for name, data in ents:
        while len(s) % 16:
            s.append(0)
        offs.append(len(s))
        s += data
    while len(s) % 4:
        s.append(0)
    toc_off = len(s)
    s += struct.pack("<I", 0x12345678)
    for (name, data), off in zip(ents, offs):
        s += b"\x10" + struct.pack("<QII", srmods.fnv1a64_upper(name), off >> 4, len(data))
        s += name.encode("latin1").ljust(name_width, b"\0")
    struct.pack_into("<III", s, 0x0C, len(ents), toc_off, 0)
    struct.pack_into("<I", s, 0x18, len(s) - toc_off)
    s[0x20:0x27] = bytes([0, 0, 8, 4, 4, 0, 4])
    struct.pack_into("<II", s, 0x28, 1, name_width)
    return bytes(s)


def w(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(data if isinstance(data, bytes) else data.encode("utf-8"))


