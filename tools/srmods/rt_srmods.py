def test_srpatch():
    base = bytes(range(256)) * 40
    out = base[:500] + b"OUR NEW BYTES" + b"\0" * 40 + base[600:5000] + base[100:180]
    p, st = srpatch.encode(base, out)
    check(srpatch.apply(base, p) == out and st["add_bytes"] < 40, "P1 encode/apply round trip; ADD only our bytes (%d B)" % st["add_bytes"])
    filebuf = b"x" * 1000 + b"GAME-BYTES-ELSEWHERE-IN-THE-FILE-0123456789" + b"y" * 1000
    out2 = base[:64] + b"GAME-BYTES-ELSEWHERE-IN-THE-FILE-0123456789"
    p2, st2 = srpatch.encode(base, out2, file=filebuf)
    ok, _, dirty, got = srpatch.clean_check(base, p2, filebuf)
    check(ok and got == out2 and st2["copyf_bytes"] >= 32, "P2 a window found elsewhere in the FILE becomes a COPYF (clean)")
    bad = bytearray(p)
    bad[-5] ^= 0xFF
    try:
        srpatch.apply(base, bytes(bad))
        check(False, "P3 a corrupted patch is refused")
    except srpatch.PatchError:
        check(True, "P3 a corrupted patch is refused")
    try:
        srpatch.apply(base[1:], p)
        check(False, "P4 another base is refused")
    except srpatch.PatchError:
        check(True, "P4 another base is refused")


def test_srvfs(full):
    data = os.path.join(REPO, "Superman Returns (USA)", "DATA")
    names = sorted(os.listdir(data)) if full else ["text.AST", "preload.AST", "ui.AST"]

    def rebuild_all(src):
        c = srvfs.Bgfa(src)
        for e in c.entries:
            if e.data.is_bgfa():
                try:
                    e.data = rebuild_all(e.data)
                except srvfs.VfsError:
                    pass
        c.changed = True
        return c.build()
    for n in names:
        if not n.upper().endswith(".AST"):
            continue
        disc = srvfs.Src.file(os.path.join(data, n))
        check(rebuild_all(disc).equals(disc), "V1 identity rebuild of %s (every nested container) is byte-exact" % n)


