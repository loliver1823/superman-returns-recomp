def py_summary(r):
    lines = []
    for m in r["mods"]:
        lines.append("mod %s %s enabled=%d mounted=%d category=%s" % (m.id, m.status, 1 if m.enabled else 0, 1 if m.mounted else 0, m.category))
    for f in r["features"]:
        lines.append("port %s %s applied=%d" % (f.id, f.status, 1 if f.applied else 0))
    for L in r["layers"]:
        lines.append("layer %s %s" % ("port" if L["port"] else "mod", L["id"]))
        for root in L["roots"]:
            files = []
            for rel, full in srmods.layer_files(root):
                h = hashlib.sha256(open(full, "rb").read()).hexdigest()
                hid = " hidden" if os.path.normcase(os.path.abspath(full)) in r["hidden"] else ""
                files.append("  file %s %s%s" % (rel, h, hid))
            lines += sorted(files)
    conf = sorted("conflict %s : %s > %s" % c for c in r["conflicts"])
    return [l for l in lines if not l.startswith("conflict")] + conf


def cpp_summary(exe, root, mods="-", port="-", automated="0"):
    out = subprocess.run([exe, "--mod-manager-dump", root, mods, port, automated], capture_output=True, text=True,
                         env=dict(os.environ, SR_MODS="0"), timeout=600)
    if out.returncode:
        raise RuntimeError("native mod-manager dump failed (%d): %s" % (out.returncode, out.stderr[-2000:]))
    lines = [l.rstrip("\r") for l in out.stdout.splitlines() if l.strip()]
    lines = [l for l in lines if l.startswith(("mod ", "port ", "layer ", "  file ", "conflict "))]
    if not lines:
        raise RuntimeError("native mod-manager dump returned no catalogue: stdout=%r stderr=%r" % (out.stdout[-2000:], out.stderr[-2000:]))
    conf = sorted(l for l in lines if l.startswith("conflict "))
    return [l for l in lines if not l.startswith("conflict ")] + conf


