"""Generate the cloth tangent body with sized scratch arrays, unchanged math.

The body comes from the local generated game code, never shipped as a second
copy of game source. Refuse a changed body until its stack contract is reviewed.
"""
import argparse
import hashlib
from pathlib import Path

BODY_SHA256 = "bad37ac523d7f7019c1a34c0dfa17dbcca91a7730214f265901a4031456f6a33"


def generate(source):
    marker = "PPC_FUNC_IMPL(__imp__sub_822C6E30) {"
    begin = source.index(marker)
    end = source.index("\n__attribute__", begin)
    body = source[begin:end].rstrip()
    if hashlib.sha256(body.encode()).hexdigest() != BODY_SHA256:
        raise ValueError("cloth tangent body changed; review its stack layout before regenerating")
    replacements = {
        marker: ("static void clothTangentsSized(PPCContext& __restrict ctx, uint8_t* base, "
                 "const sr::kernel::ClothScratchLayout& layout) {", 1),
        " + 2416": (" + layout.tangent1", 8),
        " + 7216": (" + layout.tangent2", 7),
        " + 12132": (" + (layout.frame + 20)", 5),
        "-12112 +": ("-int32_t(layout.frame) +", 1),
        " + 12112": (" + layout.frame", 1),
        "ctx.r5.s64 = 4800;": ("ctx.r5.s64 = layout.accumulationBytes;", 2),
    }
    for old, (new, count) in replacements.items():
        if body.count(old) != count:
            raise ValueError("unexpected cloth scratch reference: " + old)
        body = body.replace(old, new)
    return "// Generated by tools/regen/cloth_capacity.py; do not edit.\n" + body + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    generated = generate(args.source.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    if not args.output.exists() or args.output.read_text(encoding="utf-8") != generated:
        args.output.write_text(generated, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
