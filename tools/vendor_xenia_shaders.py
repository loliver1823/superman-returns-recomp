#!/usr/bin/env python3
"""vendor_xenia_shaders.py - vendor the Xenia shader sources the renderer's precompiled shaders come from.

The renderer embeds 41 of Xenia's Direct3D 12 shaders as DXBC byte arrays (EDRAM resolves and texture
loads in gfx/d3d12_pm4_shmem.cpp; FXAA and the guest-output bilinear / AMD FidelityFX CAS / FSR passes in
gfx/d3d12_present_chain.cpp). The build compiles them from source with the Windows SDK's fxc.exe, with
the arguments of Xenia's own build (cmake/xenia_shaders.cmake), so no Xenia checkout is needed. This
script copies those sources and everything they #include into third_party/xenia-shaders/, keeping
Xenia's directory layout (src/xenia/..., third_party/...) so every relative #include resolves
unchanged. Each file is the committed blob, byte for byte (each keeps its own licence header), and
third_party/xenia-shaders/SOURCES.txt records where every file came from and its SHA-256.

    python tools/vendor_xenia_shaders.py --xenia <xenia-canary checkout>   # (re)vendor
    python tools/vendor_xenia_shaders.py --check                            # SOURCES.txt hashes hold

The shader list is third_party/xenia-shaders/shaders.txt (CMake reads the same file). The include
closure is a superset: every `#include "..."` line counts, whatever #if guards it.
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(REPO, "third_party", "xenia-shaders")
LIST = os.path.join(DEST, "shaders.txt")
SOURCES = os.path.join(DEST, "SOURCES.txt")
INCLUDE = re.compile(rb'^\s*#\s*include\s*"([^"]+)"', re.M)
# Xenia's submodules that hold vendored shader headers: path -> licence file (relative to Xenia's root).
SUBMODULES = ["third_party/FidelityFX-CAS", "third_party/FidelityFX-FSR"]
LICENCES = ["LICENSE",                                   # Xenia, BSD-3-Clause (Ben Vanik)
            "third_party/fxaa/LICENSE",                  # NVIDIA FXAA 3.11, BSD-3-Clause
            "third_party/FidelityFX-CAS/LICENSE.txt",    # AMD FidelityFX CAS, MIT
            "third_party/FidelityFX-FSR/license.txt"]    # AMD FidelityFX FSR 1, MIT


def shader_list():
    with open(LIST, encoding="utf-8") as f:
        return [l.strip() for l in f if l.strip() and not l.lstrip().startswith("#")]


def git(repo, *args):
    r = subprocess.run(["git", "-C", repo] + list(args), capture_output=True)
    if r.returncode != 0:
        sys.exit("git -C %s %s failed: %s" % (repo, " ".join(args), r.stderr.decode(errors="replace").strip()))
    return r.stdout


def blob(xenia, rel):
    """(bytes, repo label, commit) of the committed file rel (relative to Xenia's root)."""
    for sub in SUBMODULES:
        if rel.startswith(sub + "/"):
            repo = os.path.join(xenia, *sub.split("/"))
            commit = git(repo, "rev-parse", "HEAD").decode().strip()
            return git(repo, "cat-file", "blob", "%s:%s" % (commit, rel[len(sub) + 1:])), sub, commit
    commit = git(xenia, "rev-parse", "HEAD").decode().strip()
    return git(xenia, "cat-file", "blob", "%s:%s" % (commit, rel)), "xenia-canary", commit


def exists(xenia, rel):
    for sub in SUBMODULES:
        if rel.startswith(sub + "/"):
            repo, rel = os.path.join(xenia, *sub.split("/")), rel[len(sub) + 1:]
            break
    else:
        repo = xenia
    return subprocess.run(["git", "-C", repo, "cat-file", "-e", "HEAD:" + rel], capture_output=True).returncode == 0


def closure(xenia):
    seen, todo = [], list(shader_list())
    while todo:
        rel = todo.pop(0)
        if rel in seen:
            continue
        seen.append(rel)
        data, _, _ = blob(xenia, rel)
        for inc in INCLUDE.findall(data):
            path = os.path.normpath(os.path.join(os.path.dirname(rel), inc.decode())).replace("\\", "/")
            if path.startswith(".."):
                sys.exit("%s includes %s, outside the Xenia tree" % (rel, inc.decode()))
            if not exists(xenia, path):
                # e.g. FXAA3_11.h's usage notes: `  #include "Fxaa3_11.h"` inside a comment
                print("note: %s names %s, which is not in the tree (a comment or a dead branch); skipped"
                      % (rel, inc.decode()))
                continue
            todo.append(path)
    return sorted(seen)


def vendor(xenia):
    xenia = os.path.abspath(xenia)
    dirty = git(xenia, "status", "--porcelain", "--", "src/xenia/gpu/shaders", "src/xenia/ui/shaders",
                "third_party/fxaa").decode().strip()
    if dirty:
        print("note: the checkout has local changes in its shader directories; the committed blobs are used:\n"
              + dirty)
    files = closure(xenia) + LICENCES
    head = git(xenia, "rev-parse", "HEAD").decode().strip()
    lines = ["# GENERATED by tools/vendor_xenia_shaders.py - do not edit. Every file below is the committed",
             "# blob of the named repository at the named commit, byte for byte (each keeps its own header).",
             "# xenia-canary  https://github.com/xenia-canary/xenia-canary  @%s" % head]
    for sub in SUBMODULES:
        commit = git(os.path.join(xenia, *sub.split("/")), "rev-parse", "HEAD").decode().strip()
        url = git(xenia, "config", "-f", ".gitmodules", "--get", "submodule.%s.url" % sub).decode().strip()
        lines.append("# %s  %s  @%s (Xenia's submodule)" % (sub, url, commit))
    lines.append("# <sha256>  <path>  <origin>")
    for rel in files:
        data, origin, commit = blob(xenia, rel)
        out = os.path.join(DEST, *rel.split("/"))
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "wb") as f:
            f.write(data)
        lines.append("%s  %s  %s@%s" % (hashlib.sha256(data).hexdigest(), rel, origin, commit[:10]))
    with open(SOURCES, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("vendored %d files (%d shaders + include closure + %d licences) from xenia-canary @%s into %s"
          % (len(files), len(shader_list()), len(LICENCES), head[:10], os.path.relpath(DEST, REPO)))


def check():
    bad = n = 0
    with open(SOURCES, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            sha, rel, _ = line.split()
            n += 1
            p = os.path.join(DEST, *rel.split("/"))
            if not os.path.isfile(p):
                print("MISSING %s" % rel)
                bad += 1
            elif hashlib.sha256(open(p, "rb").read()).hexdigest() != sha:
                print("CHANGED %s (a CRLF checkout? third_party/xenia-shaders is -text in .gitattributes)" % rel)
                bad += 1
    missing = [s for s in shader_list() if not os.path.isfile(os.path.join(DEST, *s.split("/")))]
    for s in missing:
        print("shaders.txt names %s, which is not vendored" % s)
    print("%d vendored files, %d bad, %d listed shaders missing" % (n, bad, len(missing)))
    return 1 if bad or missing else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--xenia", help="a xenia-canary checkout (with its FidelityFX submodules)")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        return check()
    if not a.xenia:
        ap.error("--xenia <checkout> or --check")
    vendor(a.xenia)
    return 0


if __name__ == "__main__":
    sys.exit(main())
