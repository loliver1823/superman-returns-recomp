#!/usr/bin/env python3
"""gen_xesl_embed.py - embed the Xenia shader sources the native resolve compiles.

gfx/native_resolve.inc reads host render targets. Its native include closure drops
the unused EDRAM buffer declarations, loads and byte-address helpers from Xenia's
resolve header. The original vendored sources remain untouched for Oracle shader
builds. Every embedded file retains its BSD-3 header (Xenia, Ben Vanik).

    python tools/gen_xesl_embed.py      # rewrites third_party/xenia-shaders/xesl_embed.inc

The sources are the vendored copies in third_party/xenia-shaders/src/xenia (tools/vendor_xenia_shaders.py);
re-run after re-vendoring. The output names the source commit (third_party/xenia-shaders/SOURCES.txt).
"""
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "third_party", "xenia-shaders", "src", "xenia")
SOURCES = os.path.join(REPO, "third_party", "xenia-shaders", "SOURCES.txt")
FILES = [
    "gpu/shaders/endian.xesli",
    "gpu/shaders/pixel_formats.xesli",
    "gpu/shaders/sr_resolve.xesli",
    "gpu/shaders/texture_address.xesli",
    "gpu/shaders/texture_load.xesli",  # iter-466 res4k: the direct scaled texture load
    "ui/shaders/xesl.xesli",
]
OUT = os.path.join(REPO, "third_party", "xenia-shaders", "xesl_embed.inc")
DELIM = "XESL"


def native_resolve_text(text):
    """Exact deletions from the pinned upstream header; fail on source drift."""
    def remove(start, end):
        nonlocal text
        if text.count(start) != 1:
            raise ValueError("resolve trim anchor changed: " + start)
        first = text.index(start)
        last = text.index(end, first) + len(end)
        text = text[:first] + text[last:]

    remove('#include "edram.xesli"', '\n')
    remove('#ifndef XE_RESOLVE_CLEAR\n  #if XE_RESOLVE_COPY_EDRAM_BYTE_BUFFER_ALIGNMENT',
           'byte_buffer_binding_xe(xe_resolve_edram, buffer(2))\n#endif\n')
    remove('uint XeResolveEdramPixelStrideBytes(', '\n}\n')
    remove('  uint XeResolveColorCopySourcePixelAddressBytesYHalfPixelOffsetFilling(', '\n  }\n')
    remove('  #if XE_RESOLVE_COPY_EDRAM_BYTE_BUFFER_ALIGNMENT == 4',
           '  #endif  // XE_RESOLVE_COPY_EDRAM_BYTE_BUFFER_ALIGNMENT == 4\n')
    for forbidden in ('XeEdramOffsetBytes', 'XeResolveLoad', 'XE_RESOLVE_COPY_EDRAM_',
                      'XeResolveEdramPixelStrideBytes', '#include "edram.xesli"'):
        if forbidden in text:
            raise ValueError("native resolve retains " + forbidden)
    return ('// Native host-target include, generated by tools/gen_xesl_embed.py.\n'
            '// EDRAM buffer access removed; format packing and destination addressing unchanged.\n' + text)


def main():
    commit = "?"
    with open(SOURCES, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# xenia-canary "):
                commit = line.split("@")[-1].strip()[:7]
    parts = [
        "// GENERATED by tools/gen_xesl_embed.py - do not edit.\n",
        f"// Xenia shader sources (xenia-canary @{commit}, src/xenia/...), BSD-3-Clause\n",
        "// sr_resolve.xesli omits unused EDRAM-buffer code; other files are verbatim.\n",
        "// (Copyright Ben Vanik; each file keeps its own header). Used by gfx/native_resolve.inc.\n",
        "struct XeslEmbedFile { const char* path; const char* text; };\n",
        "static const XeslEmbedFile kXeslEmbed[] = {\n",
    ]
    for rel in FILES:
        source = rel.replace('/sr_resolve.xesli', '/resolve.xesli')
        with open(os.path.join(SRC, *source.split("/")), encoding="utf-8") as f:
            text = f.read()
        if rel.endswith('/sr_resolve.xesli'):
            text = native_resolve_text(text)
        assert f"){DELIM}\"" not in text, rel
        parts.append(f'    {{"{rel}", R"{DELIM}(' + text + f'){DELIM}"}},\n')
    parts.append("};\n")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(parts))
    print(f"wrote {OUT} ({len(FILES)} files, xenia-canary @{commit})")


if __name__ == "__main__":
    main()
