def run_suite(mod_path, timeout=900):
    env = dict(os.environ, XTR_DRAWS_PATH=mod_path, PYTHONIOENCODING='utf-8')
    t0 = time.time()
    p = subprocess.run([sys.executable, SUITE], env=env, capture_output=True, text=True,
                       encoding='utf-8', errors='replace', timeout=timeout)
    m = VERDICT.search(p.stdout or '')
    return p.returncode, m, p.stdout, p.stderr, time.time() - t0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--only', help='run one mutant by name')
    ap.add_argument('--verbose', action='store_true', help='print the failing test names per mutant')
    a = ap.parse_args(argv)
    if a.list:
        for name, cls, _f, _r in MUTANTS:
            print('%-48s %s' % (name, cls))
        return 0
    src = open(TOOL, encoding='utf-8').read()
    selected = [m for m in MUTANTS if not a.only or m[0] == a.only]
    if not selected:
        print('no such mutant:', a.only)
        return 2
    names = [m[0] for m in MUTANTS]
    if len(set(names)) != len(names):
        print('duplicate mutant names:', sorted({n for n in names if names.count(n) > 1}))
        return 2

    tmp = tempfile.mkdtemp(prefix='xtr_draws_mut_')
    try:
        # control: the unmutated copy must pass clean through the same path
        ctl = os.path.join(tmp, 'xtr_draws.py')
        shutil.copyfile(TOOL, ctl)
        rc, m, out, err, dt = run_suite(ctl)
        if m is None or rc != 0 or int(m.group(3)) or int(m.group(4)):
            print('CONTROL FAILED (rc=%d): %s' % (rc, m.group(0) if m else 'no verdict line'))
            print(out[-3000:], err[-3000:])
            return 1
        print('control: %s (%.1fs)' % (m.group(0), dt))

        killed, survived, crashed, anchor_bad = [], [], [], []
        for name, cls, find, repl in selected:
            c = src.count(find)
            if c != 1:
                anchor_bad.append((name, c))
                print('%-48s ANCHOR x%d' % (name, c))
                continue
            mut = os.path.join(tmp, 'xtr_draws_mut.py')
            with open(mut, 'w', encoding='utf-8', newline='\n') as f:
                f.write(src.replace(find, repl))
            rc, m, out, err, dt = run_suite(mut)
            if m is None:
                crashed.append(name)
                tail = (err or out).strip().splitlines()[-1:] or ['']
                print('%-48s CRASH (no verdict; NOT detection) %s' % (name, tail[0][:80]))
                continue
            failed, exc = int(m.group(3)), int(m.group(4))
            failing = re.findall(r'^FAIL  (.*)$', out, re.M)
            if failed > 0:
                killed.append(name)
                print('%-48s killed  failed=%d exceptions=%d  (%.1fs)%s'
                      % (name, failed, exc, dt, ('  ' + '; '.join(failing[:3])) if a.verbose else ''))
            else:
                survived.append(name)
                print('%-48s SURVIVED  %s' % (name, m.group(0)))
        print()
        print('MUTATION SUMMARY: mutants=%d killed=%d survived=%d crashed=%d anchor_errors=%d'
              % (len(selected), len(killed), len(survived), len(crashed), len(anchor_bad)))
        classes = sorted({cls for _n, cls, _f, _r in selected})
        for cls in classes:
            k = [n for n, c, _f, _r in selected if c == cls and n in killed]
            t = [n for n, c, _f, _r in selected if c == cls]
            print('  %-26s %d/%d killed' % (cls, len(k), len(t)))
        if survived:
            print('  survived:', ', '.join(survived))
        if crashed:
            print('  crashed :', ', '.join(crashed))
        if anchor_bad:
            print('  anchors :', ', '.join('%s(x%d)' % ab for ab in anchor_bad))
        return 0 if not (survived or crashed or anchor_bad) else 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == '__main__':
    sys.exit(main())
