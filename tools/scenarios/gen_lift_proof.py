"""Generates tools/scenarios/lift_proof.json (iter-465 playthrough lane): after SKIP ends a minigame, Superman
is lifted clear of its start circle and the game does not restart it. Chapter-2 save (port features on):
LOAD GAME -> METROPOLIS -> pause > OPTIONS > (GAME) DEV TOOLS > LEVEL SKIP (lane E L-c) > SIDE MISSIONS > RACE #95 (starts
it); the companion lift_proof_play.txt presses F10 during the race, then F10 again 20 s after the lift: the
second must be refused 'nothing_active' (no restart). Same gates as skip_chapter_proof.json.
"""
import json
import os

import gen_devtools_skip_menu as G
import gen_skip_chapter_proof as C

FS = r"\[SR_FSCMD\]"
head = [s for s in C.steps if not s["name"].startswith("chapter-") and s["name"] != "after-chapters"]
cut = [i for i, s in enumerate(head) if s["name"] == "metropolis"][0]
steps = head[:cut + 1] + [{"name": "settle", "dwellMs": 20000}]
steps += G.open_levelskip("race")
steps += [G.k("race-down-to-side", "DOWN", pulses=2, dwell=1200),
          G.k("race-open-side", "A", FS + r".*SR_Log 'menu show sidemissions", dwell=4000),
          G.k("race-pick-95", "A", r"\[DEVTOOL\] levelskip armed plan=.*menu_side_95", ms=10000, dwell=4000)]
steps += G.close_to_game("race")
steps += [{"name": "skip", "await": r"\[DEVTOOL\] skip_mission ticket=\d+ active", "timeoutMs": 300000},
          {"name": "lift", "await": r"\[DEVTOOL\] act=levelskip\.lift|refused act=levelskip\.lift", "timeoutMs": 120000},
          {"name": "no-restart", "purpose": "F10 again 20 s later: refused nothing_active = the race did not restart",
           "await": r"refused act=levelskip\.skip_mission ticket=\d+ why=nothing_active",
           "timeoutMs": 120000},
          {"name": "after", "dwellMs": 15000}]
doc = {"name": "lift-proof", "purpose": "iter-465: SKIP ends a race and Superman is lifted clear; no restart "
       "(generated by gen_lift_proof.py).",
       "gates": "SR_KB_PAD_OBS=1,SR_PRESENT_DUMP=1,SR_PRESENT_DUMP_SPARSE_EVERY=30,SR_PRESENT_DUMP_SPARSE_CAP=1500",
       "steps": steps}
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "lift_proof.json")
with open(out, "w", newline="\n") as f:
    json.dump(doc, f, indent=1)
print(out, len(steps))
