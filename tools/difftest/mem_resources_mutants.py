def sh(cmd, cwd, timeout=1800):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout)
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def apply(tree, rel, old, new):
    path = os.path.join(tree, rel)
    with open(path, "rb") as fh:
        raw = fh.read()
    crlf = b"\r\n" in raw
    text = raw.decode("utf-8")
    o, n = old, new
    if crlf:  # the tree may be checked out with CRLF line ends
        o, n = old.replace("\n", "\r\n"), new.replace("\n", "\r\n")
    hits = text.count(o)
    if hits != 1:
        return None, "the mutant's text matches %d times in %s" % (hits, rel)
    with open(path, "wb") as fh:
        fh.write(text.replace(o, n).encode("utf-8"))
    return raw, None


def restore(tree, rel, raw):
    with open(os.path.join(tree, rel), "wb") as fh:
        fh.write(raw)


def run_group(tree, group, test, only, rows):
    bad = 0
    rc, out = sh(test, tree)
    rows.append(("clean", os.path.basename(test[4]), "exit %d" % rc,
                 "PASS" if rc == 0 else "ERROR (the clean tree must pass)"))
    bad += rc != 0
    for mid, rel, old, new, what in group:
        if only and mid not in only:
            continue
        if rel == "kernel/gpu_command_processor.cpp" and os.path.isfile(os.path.join(tree, "kernel/gpu_submit.cpp")):
            rel = "kernel/gpu_submit.cpp"
        raw, err = apply(tree, rel, old, new)
        if err:
            rows.append((mid, what, err, "ERROR"))
            bad += 1
            continue
        try:
            rc, out = sh(test, tree)
        finally:
            restore(tree, rel, raw)
        fails = [ln for ln in out.splitlines() if ln.startswith("FAIL:")]
        ev = fails[0][6:120] if fails else (out.strip().splitlines() or ["-"])[-1][:120]
        rows.append((mid, what, "exit %d: %s" % (rc, ev), "KILLED" if rc != 0 else "SURVIVED"))
        bad += rc == 0
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", default=".")
    ap.add_argument("--build-dir", default="build")
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--only", default="")
    ap.add_argument("--no-build", action="store_true")
    ap.add_argument("--family-fixture", help="memres6: also run --mem-resources-family-test on this fixture for the "
                                             "interval-narrowing mutants (information beside the suite's verdict)")
    a = ap.parse_args(argv)
    tree = os.path.abspath(a.tree)
    only = {x for x in a.only.split(",") if x}
    exe = os.path.join(tree, a.build_dir, "difftest.exe" if os.name == "nt" else "difftest")
    py = [sys.executable, "-I", "-X", "utf8"]
    wiring = py + [os.path.join(tree, "tools", "perf", "test_mem_resources_wiring.py"), "--root", tree]
    grader = py + [os.path.join(tree, "tools", "perf", "test_mem_res_census.py")]
    rows = []
    bad = run_group(tree, WIRING, wiring, only, rows)
    bad += run_group(tree, GRADER, grader, only, rows)

    if not a.no_build:
        build = ["cmake", "--build", a.build_dir, "--target", "difftest", "-j", str(a.jobs)]
        suite = [exe, "--mem-resources-test"]
        for mid, rel, old, new, what in BUILD:
            if only and mid not in only:
                continue
            raw, err = apply(tree, rel, old, new)
            if err:
                rows.append((mid, what, err, "ERROR"))
                bad += 1
                continue
            fam = ""
            try:
                brc, bout = sh(build, tree)
                if brc != 0:
                    rows.append((mid, what, "the mutant did not build (exit %d)" % brc, "ERROR"))
                    bad += 1
                    continue
                rc, out = sh(suite, tree, 600)
                if a.family_fixture and mid in FAMILY_MUTANTS:  # (information: the traced draws' differential test too)
                    frc, _ = sh([exe, "--mem-resources-family-test", a.family_fixture], tree, 1800)
                    fam = "; family test exit %d (%s)" % (frc, "caught" if frc else "not caught")
            finally:
                restore(tree, rel, raw)
            fails = [ln for ln in out.splitlines() if ln.startswith("FAIL:")]
            rows.append((mid, what, "exit %d, %d checks failed: %s%s" % (rc, len(fails), fails[0][6:100] if fails else "-",
                                                                       fam),
                         "KILLED" if rc != 0 else "SURVIVED"))
            bad += rc == 0
        brc, _ = sh(build, tree)
        rc, out = sh(suite, tree, 600) if brc == 0 else (brc, "")
        rows.append(("restored", "difftest rebuilt from the restored sources", "build %d, suite exit %d" % (brc, rc),
                     "PASS" if brc == 0 and rc == 0 else "ERROR"))
        bad += not (brc == 0 and rc == 0)

    print("%-9s %-9s %s" % ("mutant", "verdict", "what it breaks / the evidence"))
    for mid, what, ev, verdict in rows:
        print("%-9s %-9s %s\n%20s %s" % (mid, verdict, what, "", ev))
    print("mem.resources mutants: %s" % ("every mutant killed" if not bad else "%d survived or errored" % bad))
    return bad


if __name__ == "__main__":
    sys.exit(main())
