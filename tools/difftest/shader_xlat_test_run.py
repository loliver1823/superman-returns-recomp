def build(src, work, exe, common):
    """src = the (possibly mutated) source tree root (holds gfx/); common = prebuilt objects."""
    objs = list(common)
    core = ["-std=c++17", "-O2", "-DNDEBUG", "-DNOMINMAX", "-DWIN32_LEAN_AND_MEAN", "-I" + src, "-I" + REPO,
            "-I" + os.path.join(REPO, "gfx"),
            "-I" + os.path.join(DXC, "inc")]
    game = ["-std=c++20", "-O1", "-DNOMINMAX", "-DWIN32_LEAN_AND_MEAN", "-D_CRT_SECURE_NO_WARNINGS",
            "-DSR_HAVE_XENOS_XLAT=1", "-Wno-deprecated-declarations", "-I" + src, "-I" + REPO,
            "-I" + os.path.join(REPO, "gfx"), "-I" + os.path.join(REPO, "app")]
    units = [(os.path.join(src, "gfx", "xenos_bridge.cpp"), xr_tu() + ["-I" + src]),
             (os.path.join(src, "gfx", "shader_xlat_core.cpp"), core),
             (os.path.join(src, "gfx", "shader_cache.cpp"), game),
             (os.path.join(src, "gfx", "shader_runtime_xlat.cpp"), game),
             (os.path.join(REPO, "tools", "difftest", "shader_xlat_test.cpp"), game),
             (os.path.join(REPO, "app", "log.cpp"), game),
             # ShaderCache::hashUcode's AVX2 XXH3 (iter-465, run-time selected) and the HITCH hooks
             # (iter-466) that shader_runtime_xlat.cpp times translations with, OFF as in the game.
             (os.path.join(REPO, "gfx", "hash_avx2.cpp"), game + ["-mavx2"]),
             # NativeShaderCode (CachedShader's bytecode owners, shader_cache.cpp buildEntry); the link
             # failed without it since the native pipeline cache landed (dcb, 2026-10-14).
             (os.path.join(REPO, "gfx", "native_pipeline.cpp"), game),
             (os.path.join(REPO, "tools", "difftest", "shader_xlat_test_stubs.cpp"), game)]
    od = os.path.join(work, os.path.basename(exe) + ".obj")
    os.makedirs(od, exist_ok=True)
    for i, (f, flags) in enumerate(units):
        o = os.path.join(od, "%d_%s.o" % (i, os.path.basename(f)))
        if not run([CXX] + flags + ["-c", f, "-o", o]):
            return False
        objs.append(o)
    return run([CXX] + objs + ["-lole32", "-o", exe])


