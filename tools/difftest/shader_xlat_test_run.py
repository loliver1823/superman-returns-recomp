def pinned_corpus(work):
    src = os.path.join(REPO, "archive", "v1_arena", "stage", "missing_vs", "corpus.txt")
    if not os.path.isfile(src):
        return []
    carved = os.path.join(work, "shaders_carved_pinned")
    shutil.rmtree(carved, ignore_errors=True)
    os.makedirs(carved)
    skipped = []
    for n in sorted(os.listdir(os.path.join(REPO, "data", "shaders_carved"))):
        if "data/shaders_carved/" + n in PINNED_EXCLUDE:
            skipped.append(n)
            continue
        shutil.copy2(os.path.join(REPO, "data", "shaders_carved", n), os.path.join(carved, n))
    out = os.path.join(work, "corpus_pinned.txt")
    with open(src, encoding="utf-8", errors="replace") as f, open(out, "w", encoding="utf-8") as g:
        for line in f:
            parts = line.split(None, 1)
            if len(parts) == 2 and parts[1].strip() == "data/shaders_carved":
                line = "%s %s\n" % (parts[0], carved.replace("\\", "/"))
            g.write(line)
    print("pinned corpus %s (data/shaders_carved without %s)" % (out, ", ".join(skipped) or "nothing"))
    return ["--corpus", out]


def run_offline(pin, pout):
    """The offline XenosRecomp.exe over one directory (one batch run, as the corpus pipeline does)."""
    shutil.rmtree(pout, ignore_errors=True)
    os.makedirs(pout)
    env = {k: v for k, v in os.environ.items() if k not in ("XENOS_DUMP_HLSL", "XENOS_VSF_ONLY", "XENOS_PS_ONLY")}
    newest_src = max(os.path.getmtime(os.path.join(XR, "XenosRecomp", f)) for f in
                     ("shader_recompiler.cpp", "shader_recompiler.h", "shader_common.h", "main.cpp"))
    if os.path.getmtime(OFFLINE_EXE) < newest_src:
        print("WARNING: %s is older than its sources - rebuild it (build_xenos.bat) or T5 compares against a "
              "stale translator" % OFFLINE_EXE)
    with open(os.path.join(pout, "run.log"), "w") as log:
        subprocess.run([OFFLINE_EXE, pin, os.path.join(pout, "cache.cpp"), os.path.join(XR, "XenosRecomp",
                        "shader_common.h")], stdout=log, stderr=subprocess.STDOUT, env=env, cwd=pout)


