# build_import_census.ps1 - the logic audit's import-census Xenia (docs/LOGIC_AUDIT.md 2.0c, the oracle half of
# SR_AUDIT_IMPORTS): xenia_canary.exe from EXACTLY xenia-canary 0bd090dbe (the oracle) plus
# tools/xenia-trace/xenia_import_census.patch and tools/xenia-trace/sr_import_census.h - records only (per-export
# entries / returns / caller lr / results / first calls), off unless XENIA_IMPORT_CENSUS=<path.json> is set.
# Runs on the build worker (MSVC Build Tools 2022, CMake, Ninja, git), approved there by the orchestrator 2026-10-18;
# it never touches an installed Xenia, its config or its content:
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/xenia-trace/build_import_census.ps1 [-Root DIR]
#
# A fresh source tree (a blobless clone of upstream, beside - never inside - the zpd lane's C:\sr\scratch\zpd_xenia,
# whose tree carries other patches), its own build directory,
# and <Root>\build_census.txt (the commit, the patch / header hashes, every step's exit code, the exe hash).
# Output: <Root>\src\build\bin\Windows\Release\xenia_canary.exe (+ .pdb) and a copy of that folder in <Root>\out.
param(
  [string]$Root = 'C:\sr\scratch\s4a_xenia_census',
  [string]$Commit = '0bd090dbe979bc64959efe519aa320db8e3eb467',
  [string]$Vcvars = 'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat',
  [int]$Jobs = 12,
  # The SPIR-V shader step (tools/build/compile_shader_spirv.py) needs glslangValidator / spirv-opt / spirv-dis from
  # a Vulkan SDK: VULKAN_SDK, its bin folder. The worker has no SDK installed; a copy of those tools (+ their DLLs) sits here.
  [string]$VulkanSdk = ''
)
if (-not $VulkanSdk) { $VulkanSdk = Join-Path $Root 'vulkan_sdk' }
$ErrorActionPreference = 'Continue'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$patch = Join-Path $here 'xenia_import_census.patch'
$header = Join-Path $here 'sr_import_census.h'
$src = Join-Path $Root 'src'
$report = Join-Path $Root 'build_census.txt'
New-Item -ItemType Directory -Force $Root | Out-Null
function Note([string]$s) { Add-Content -Encoding utf8 $report $s; Write-Host $s }
Set-Content -Encoding utf8 $report ("build_import_census " + (Get-Date -Format s))

if (-not (Test-Path (Join-Path $src '.git'))) {
  # The same blobless clone as build_zpd_trace_dump.ps1 (a local clone of that partial clone would lack blobs).
  git -c core.autocrlf=true clone --filter=blob:none --no-checkout https://github.com/xenia-canary/xenia-canary.git $src
  Note ("clone exit $LASTEXITCODE")
}
Set-Location $src
git -c core.autocrlf=true checkout -f $Commit
Note ("checkout $Commit exit $LASTEXITCODE (HEAD " + (git rev-parse HEAD) + ")")
git -c core.autocrlf=true submodule update --init --recursive --jobs 8
Note ("submodules exit $LASTEXITCODE")
# Exactly the commit plus the census: reset the tree, then add the header and apply the patch.
git -c core.autocrlf=true checkout -f -- src
git clean -fdq -- src
Copy-Item -LiteralPath $header -Destination (Join-Path $src 'src\xenia\kernel\util\sr_import_census.h') -Force
Note ("header sr_import_census.h sha256 " + (Get-FileHash $header).Hash)
git apply --whitespace=nowarn --ignore-whitespace $patch
Note ("apply xenia_import_census.patch exit $LASTEXITCODE sha256 " + (Get-FileHash $patch).Hash)
Note ("tree status: " + ((git status --short) -join ' | '))
$build = Join-Path $src 'build'
New-Item -ItemType Directory -Force $build | Out-Null
# xenia-build.py writes version.h into the build directory; plain CMake does not.
@(
  '// Autogenerated (superman-recomp logic audit import census; tools/xenia-trace/build_import_census.ps1).',
  '#ifndef GENERATED_VERSION_H_', '#define GENERATED_VERSION_H_',
  '#define XE_BUILD_BRANCH "canary_experimental-srcensus"',
  ('#define XE_BUILD_COMMIT "' + $Commit + '"'),
  ('#define XE_BUILD_COMMIT_SHORT "' + $Commit.Substring(0, 7) + '"'),
  '#define XE_BUILD_DATE __DATE__', '#endif  // GENERATED_VERSION_H_'
) | Set-Content -Encoding ascii (Join-Path $build 'version.h')
$cfg = "call `"$Vcvars`" >nul && cmake -S `"$src`" -B `"$build`" -G `"Ninja Multi-Config`" -DXENIA_BUILD_TESTS=OFF"
cmd /c $cfg *> (Join-Path $Root 'configure.log')
Note ("configure exit $LASTEXITCODE")
$bld = "call `"$Vcvars`" >nul && set `"VULKAN_SDK=$VulkanSdk`" && cmake --build `"$build`" --config Release --target xenia-app -j $Jobs"
Note ("VULKAN_SDK $VulkanSdk glslangValidator present: " + (Test-Path (Join-Path $VulkanSdk 'bin\glslangValidator.exe')))
cmd /c $bld *> (Join-Path $Root 'build.log')
Note ("build exit $LASTEXITCODE")
Note ("tree after build: " + ((git status --short) -join ' | '))
$exe = Get-ChildItem $build -Recurse -Filter 'xenia_canary.exe' -ErrorAction SilentlyContinue | Select-Object -First 1
if ($exe) {
  Note ("exe " + $exe.FullName + " sha256 " + (Get-FileHash $exe.FullName).Hash)
  $out = Join-Path $Root 'out'
  if (Test-Path $out) { Remove-Item -LiteralPath $out -Recurse -Force }
  New-Item -ItemType Directory -Force $out | Out-Null
  Get-ChildItem $exe.Directory.FullName -File | Copy-Item -Destination $out   # the exe, its pdb and what it loads
  Note ("out " + ((Get-ChildItem $out | ForEach-Object { $_.Name }) -join ', '))
} else { Note 'exe MISSING' }
