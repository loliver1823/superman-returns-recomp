# build_zpd_trace_dump.ps1 - p2.zpd's Xenia oracle (docs/NATIVE_ROADMAP.md P2.12 item 14): xenia-gpu-d3d12-trace-dump
# from the oracle build's source (xenia-canary 0bd090dbe, the commit of reference/xenia-canary-oracle/build-trace's
# version.h) with tools/xenia-trace/xenia_trace_tools_headless.patch (trace playback without a window) and
# tools/xenia-trace/xenia_zpd_oracle.patch (every occlusion report Xenia retires is logged, SR_ZPD_REPORT, and the
# dump drains the queue before it exits). Runs on the build worker (MSVC Build Tools 2022, CMake, Ninja, git):
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools/xenia-trace/build_zpd_trace_dump.ps1 [-Root DIR]
#
# Output: <Root>\src\build\bin\Windows\Release\xenia-gpu-d3d12-trace-dump.exe (+ .pdb), and <Root>\build_zpd.txt
# (the commit, the patches' hashes, the configure / build exit codes).
param(
  [string]$Root = 'C:\sr\scratch\zpd_xenia',
  [string]$Commit = '0bd090dbe979bc64959efe519aa320db8e3eb467',
  [string]$Vcvars = 'C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat'
)
$ErrorActionPreference = 'Continue'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$patches = @((Join-Path $here 'xenia_trace_tools_headless.patch'), (Join-Path $here 'xenia_zpd_oracle.patch'))
$src = Join-Path $Root 'src'
$report = Join-Path $Root 'build_zpd.txt'
New-Item -ItemType Directory -Force $Root | Out-Null
function Note([string]$s) { Add-Content -Encoding utf8 $report $s; Write-Host $s }
Set-Content -Encoding utf8 $report ("build_zpd_trace_dump " + (Get-Date -Format s))

if (-not (Test-Path (Join-Path $src '.git'))) {
  git -c core.autocrlf=true clone --filter=blob:none --no-checkout https://github.com/xenia-canary/xenia-canary.git $src
  Note ("clone exit $LASTEXITCODE")
}
Set-Location $src
git -c core.autocrlf=true checkout -f $Commit
Note ("checkout $Commit exit $LASTEXITCODE")
git -c core.autocrlf=true submodule update --init --recursive --jobs 8
Note ("submodules exit $LASTEXITCODE")
# A fresh tree each time: the patches apply to the commit's own files.
git -c core.autocrlf=true checkout -f -- src
foreach ($p in $patches) {
  git apply --whitespace=nowarn --ignore-whitespace $p
  Note ("apply " + (Split-Path -Leaf $p) + " exit $LASTEXITCODE sha256 " + (Get-FileHash $p).Hash)
}
$build = Join-Path $src 'build'
New-Item -ItemType Directory -Force $build | Out-Null
# xenia-build.py writes version.h into the build directory; plain CMake does not.
@(
  '// Autogenerated (superman-recomp p2.zpd oracle trace-dump; tools/xenia-trace/build_zpd_trace_dump.ps1).',
  '#ifndef GENERATED_VERSION_H_', '#define GENERATED_VERSION_H_',
  '#define XE_BUILD_BRANCH "canary_experimental-srzpd"',
  ('#define XE_BUILD_COMMIT "' + $Commit + '"'),
  ('#define XE_BUILD_COMMIT_SHORT "' + $Commit.Substring(0, 7) + '"'),
  '#define XE_BUILD_DATE __DATE__', '#endif  // GENERATED_VERSION_H_'
) | Set-Content -Encoding ascii (Join-Path $build 'version.h')
$cfg = "call `"$Vcvars`" >nul && cmake -S `"$src`" -B `"$build`" -G `"Ninja Multi-Config`" -DXENIA_BUILD_MISC=ON -DXENIA_BUILD_TESTS=OFF"
cmd /c $cfg *> (Join-Path $Root 'configure.log')
Note ("configure exit $LASTEXITCODE")
$bld = "call `"$Vcvars`" >nul && cmake --build `"$build`" --config Release --target xenia-gpu-d3d12-trace-dump"
cmd /c $bld *> (Join-Path $Root 'build.log')
Note ("build exit $LASTEXITCODE")
# Xenia's first-run disclaimer (Emulator::Emulator, a MessageBox until HKCU\SOFTWARE\Xenia XEFLAGS has bit 0) blocks
# forever where no desktop shows it (the worker's remote session): acknowledged here, as the PC's own Xenia did.
New-Item -Path 'HKCU:\SOFTWARE\Xenia' -Force | Out-Null
New-ItemProperty -Path 'HKCU:\SOFTWARE\Xenia' -Name 'XEFLAGS' -PropertyType QWord -Value 1 -Force | Out-Null
Note ('XEFLAGS ' + (Get-ItemProperty 'HKCU:\SOFTWARE\Xenia').XEFLAGS)
$exe = Get-ChildItem $build -Recurse -Filter 'xenia-gpu-d3d12-trace-dump.exe' -ErrorAction SilentlyContinue | Select-Object -First 1
if ($exe) { Note ("exe " + $exe.FullName + " sha256 " + (Get-FileHash $exe.FullName).Hash) } else { Note 'exe MISSING' }
